import { useEffect, useRef } from "react";

export const DEMO_BANNER_TEXT = "SYNTHETIC DEMONSTRATION DATA — NOT LIVE OPERATIONS";

/**
 * Permanent, non-dismissible indicator rendered only in the static demo build.
 * It is fixed to the top of the viewport on every view.
 */
export function DemoBanner() {
  useEffect(() => {
    document.body.dataset.demo = "true";
    document.title = "Apex Operator Console — Synthetic Demo";
  }, []);
  // Publish the banner height so sticky guidance chrome can sit directly beneath it.
  const ref = useRef<HTMLDivElement>(null);
  useEffect(() => {
    const element = ref.current;
    if (!element) return undefined;
    const publish = () => document.documentElement.style.setProperty("--demo-banner-h", `${element.offsetHeight}px`);
    publish();
    if (typeof ResizeObserver === "undefined") return undefined;
    const observer = new ResizeObserver(publish);
    observer.observe(element);
    return () => observer.disconnect();
  }, []);
  return (
    <div ref={ref} className="demo-banner" role="status" aria-live="polite" data-testid="demo-banner">
      <strong>{DEMO_BANNER_TEXT}</strong>
      <span>
        Read-only snapshot generated by Apex's own fixture services. No live system, account, credential or
        market connection is behind this page.
      </span>
    </div>
  );
}
