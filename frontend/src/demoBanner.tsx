import { useEffect } from "react";

export const DEMO_BANNER_TEXT = "SYNTHETIC DEMONSTRATION DATA — NOT LIVE OPERATIONS";

/**
 * Permanent, non-dismissible indicator rendered only in the static demo build.
 * It is fixed to the top of the viewport on every view.
 */
export function DemoBanner() {
  useEffect(() => {
    document.body.dataset.demo = "true";
    document.title = "Apex Operator Console — Synthetic Demo";
  }, []);
  return (
    <div className="demo-banner" role="status" aria-live="polite" data-testid="demo-banner">
      <strong>{DEMO_BANNER_TEXT}</strong>
      <span>
        Read-only snapshot generated by Apex's own fixture services. No live system, account, credential or
        market connection is behind this page.
      </span>
    </div>
  );
}
